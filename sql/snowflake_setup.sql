
-- AtmoSync Snowflake Data Warehouse Setup

CREATE DATABASE IF NOT EXISTS ATMOSYNC_DB;

CREATE SCHEMA IF NOT EXISTS ATMOSYNC_DB.RAW_DATA;

CREATE TABLE IF NOT EXISTS ATMOSYNC_DB.RAW_DATA.SHIPMENT_SENSOR_DATA (
    SHIPMENT_ID VARCHAR(20),
    PRODUCT VARCHAR(50),
    ORIGIN VARCHAR(100),
    DESTINATION VARCHAR(100),
    TEMPERATURE FLOAT,
    HUMIDITY FLOAT,
    TIMESTAMP DATETIME
);

-- CSV File Format
CREATE OR REPLACE FILE FORMAT ATMOSYNC_DB.RAW_DATA.SHIPMENT_CSV_FORMAT
    TYPE = CSV
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    EMPTY_FIELD_AS_NULL = TRUE;

-- Internal Snowflake Stage
CREATE OR REPLACE STAGE ATMOSYNC_DB.RAW_DATA.SHIPMENT_STAGE
    FILE_FORMAT = ATMOSYNC_DB.RAW_DATA.SHIPMENT_CSV_FORMAT;

